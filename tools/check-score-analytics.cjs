const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
process.chdir(root);
const memory = new Map();
const ctx = vm.createContext({ localStorage: { getItem: k => memory.get(k) ?? null, setItem: (k,v) => memory.set(k,v) }, console });
const source = fs.readFileSync('app.js', 'utf8').replace('    addBook(b) {', '    inspect: { books, partScores, collectScoreData, collectQuestionTypeStats, questionTypesByQuestion },\n    addBook(b) {');
vm.runInContext(source + '\nglobalThis.api = IELTS;', ctx);
const api = ctx.api, helpers = api.inspect;
const group = (instr, qs) => ({type:'html', instr, html: qs.map(q => '[['+q+']]').join(' ')});
const passage = {groups: [group('Complete the table below.', [1,2]), {type:'choice', instr:'TRUE FALSE NOT GIVEN', choices:['TRUE','FALSE','NOT GIVEN'], items:[{q:3},{q:4}]}]};
const book = {id:999,tests:[{n:1,reading:{passages:[passage]}}]};
api.addBook(book);
const put = (key, value) => memory.set(key, JSON.stringify(value));
const recordKey = 'ielts:999:1:reading:p1';
put(recordKey, {firstScore:1,firstMarks:{1:true,2:false,3:false},score:4,marks:{1:true,2:true,3:true,4:true},tries:3,firstTryDone:true});
let data = helpers.collectScoreData();
let stats = helpers.collectQuestionTypeStats(data.items).reading;
assert.equal(data.bySkill.reading.right,1);
assert.equal(stats.types.get('Table completion').right,1);
assert.equal(stats.types.get('Table completion').total,2);
assert.equal(stats.types.get('True / False / Not Given').total,2, 'blank first answers count as incorrect');
assert.equal(stats.classified,4);
put('ielts:999:1:reading',{firstScore:4,firstMarks:{1:true,2:true,3:true,4:true}});
assert.equal(helpers.collectScoreData().bySkill.reading.total,4,'full and part records must not duplicate questions');
assert.equal(helpers.collectScoreData().bySkill.reading.right,1,'analytics retain the established per-part first-score source');
memory.clear();
put('ielts:999:1:reading',{firstScore:0,firstMarks:{},firstTryDone:true});
data=helpers.collectScoreData();
assert.equal(data.bySkill.reading.total,4,'an entirely blank full submission still counts');
assert.equal(helpers.collectQuestionTypeStats(data.items).reading.classified,4);
memory.clear();
put(recordKey,{firstScore:2,firstTryDone:true,score:4,marks:{1:true,2:true,3:true,4:true}});
assert.equal(helpers.collectQuestionTypeStats(helpers.collectScoreData().items).reading.missingMarks,4,'later marks cannot substitute for missing first marks');
memory.clear();
put(recordKey,{score:4,marks:{1:true,2:true,3:true,4:true},tries:1});
put('ielts:history',[{id:'999:1:reading:p1',tries:3}]);
assert.equal(helpers.collectScoreData().items.length,0,'legacy repeated attempts are not first attempts');
memory.clear();
put(recordKey,{score:2,marks:{1:true,2:true},tries:1});
assert.equal(helpers.collectQuestionTypeStats(helpers.collectScoreData().items).reading.classified,4,'known single legacy attempt remains usable');
put('ielts:999:1:reading',{firstScore:1,firstMarks:{1:true},firstTryDone:true});
assert.equal(helpers.collectScoreData().bySkill.reading.right,1,'explicit full snapshot takes precedence over legacy part scores');
assert.equal(helpers.collectQuestionTypeStats(helpers.collectScoreData().items).reading.types.get('Table completion').right,1);
api.setQuestionTypeOverrides({'999:1:reading:1':['Table completion','True / False / Not Given']});
const grid = {groups:[group('Enter answers from the question paper.',[1,2,3,4])]};
assert.equal([...helpers.questionTypesByQuestion(grid,book,book.tests[0],'reading',1).values()].filter(Boolean).length,0,'mixed scanned grids must not be assigned to every type');
api.setQuestionTypeOverrides({'999:1:reading:1':['Matching headings','Notes completion']});
assert.equal([...helpers.questionTypesByQuestion(grid,book,book.tests[0],'reading',1).values()].filter(Boolean).length,0,'mixed section labels stay unresolved without question-specific evidence');
api.setQuestionTypeOverrides({'999:1:reading:1:q1':['Notes completion'],'999:1:reading:1:q2':['True / False / Not Given']});
const questionTypes=helpers.questionTypesByQuestion(grid,book,book.tests[0],'reading',1);
assert.equal(questionTypes.get(1),'Notes completion','question-level overrides classify mixed scanned groups precisely');
assert.equal(questionTypes.get(2),'True / False / Not Given','each scanned question can carry its own type');
assert.equal(questionTypes.get(3),null,'question-level overrides do not leak to neighboring questions');
// Load every real data file in the same order as the site and check coverage invariants.
helpers.books.length = 0; memory.clear();
const html = fs.readFileSync('index.html','utf8');
const files = [...html.matchAll(/"(data\/[^\"]+\.js)"/g)].map(m=>m[1]);
for(const file of files) vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx);
let sections=0, questions=0, mapped=0;
for(const b of helpers.books) for(const t of b.tests) for(const sk of ['reading','listening']) {
 const secs=sk==='reading'?t.reading?.passages:t.listening?.parts;
 if(!secs)continue;
 secs.forEach((sec,i)=>{const mapping=helpers.questionTypesByQuestion(sec,b,t,sk,i+1);sections++;questions+=mapping.size;mapped += [...mapping.values()].filter(Boolean).length;});
}
assert.equal(mapped,questions,'every stored question must have exactly one granular question-type mapping');
console.log(`Passed scoring checks; ${sections} sections, ${mapped}/${questions} questions have unambiguous type mappings.`);
