const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
process.chdir(path.resolve(__dirname, '..'));
const memory = new Map();
const ctx = vm.createContext({localStorage:{getItem:k=>memory.get(k)??null}});
const source = fs.readFileSync('app.js','utf8').replace('    addBook(b) {','    pickNextForSkill,\n    addBook(b) {');
vm.runInContext(source+'\nglobalThis.api=IELTS;',ctx);
const api=ctx.api;
const parts=[1,2].map(q=>({audio:'present.mp3',groups:[{type:'html',html:'[['+q+']]'}]}));
const tests=[1,2].map(n=>({n,listening:{parts:structuredClone(parts),answers:{1:'one',2:'two'}},reading:{passages:structuredClone(parts),answers:{1:'one',2:'two'}}}));
api.addBook({id:13,tests});
const put=(k,v)=>memory.set(k,JSON.stringify(v));
const full=()=>api.pickNextForSkill('listening',true);
const part=()=>api.pickNextForSkill('listening',false);
assert.equal(full(),'#/13/1/listening');
for(const saved of [{score:0,tries:3},{firstScore:null,firstTryDone:true,tries:2},{revealed:true},{checked:true},{firstMarks:{1:false}},{answers:{1:'draft'}}]) {
 memory.clear();put('ielts:13:1:listening',saved);
 assert.equal(full(),'#/13/2/listening',JSON.stringify(saved));
}
memory.clear();put('ielts:13:1:listening:p1',{score:0,tries:2});
assert.equal(full(),'#/13/2/listening');
assert.equal(part(),'#/13/1/listening/p2');
memory.clear();put('ielts:13:1:listening',{answers:{1:'draft'}});
assert.equal(part(),'#/13/1/listening/p2','full-test draft only uses its answered part');
memory.clear();put('ielts:history',[{id:'13:1:listening'}]);
assert.equal(full(),'#/13/2/listening');
assert.equal(part(),'#/13/2/listening/p1');
memory.clear();put('ielts:history',[{id:'13:1:listening:p1'}]);
assert.equal(full(),'#/13/2/listening');
assert.equal(part(),'#/13/1/listening/p2');
memory.clear();put('ielts:daily',{'2026-10-01':{lParts:['13:1:p2'],rPassages:[]}});
assert.equal(full(),'#/13/2/listening');
assert.equal(api.pickNextForSkill('reading',true),'#/13/1/reading','skills stay independent');
memory.clear();put('ielts:13:1:listening',{answers:{1:'',2:[]},part:1,marks:{},tries:0});
assert.equal(full(),'#/13/1/listening','just opening a test does not use it');
memory.clear();put('ielts:13:1:listening:p1',{score:1});put('ielts:13:2:listening:p1',{score:1});
assert.equal(full(),null,'Full test must not fall back to a part or repeat');
assert.equal(part(),'#/13/1/listening/p2');
put('ielts:13:1:listening:p2',{score:1});put('ielts:13:2:listening:p2',{score:1});
assert.equal(part(),null,'exhausted parts must not repeat');
memory.clear();
tests[0].listening.parts[0].dataMismatchWarning='Recording belongs to another test';
assert.equal(full(),'#/13/2/listening','mismatched tests must not be automatically assigned');
assert.equal(part(),'#/13/1/listening/p2','healthy parts of a flagged test remain available');
tests[0].listening.parts[1].audio='';
assert.equal(part(),'#/13/2/listening/p1','missing recordings must be skipped');
tests[1].listening.answers[1]='';
assert.equal(part(),'#/13/2/listening/p2','empty keys must be skipped');
console.log('Passed mission selection checks: legacy scores, zero scores, drafts, history, daily records, partial completion and exhaustion.');
